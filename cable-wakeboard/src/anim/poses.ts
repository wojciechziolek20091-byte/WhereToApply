/**
 * RiderPoses (spec section 1.2): every pose and clip as data, for the
 * canonical regular rider (lead = L = +x, chest toward +z). Goofy and switch
 * use mirrorPose. Degrees are rotations away from the rig's rest pose
 * (upright torso, arms hanging); see channels.ts for the axes. A hanging
 * arm swings FORWARD with a negative x rotation and OUT to its own side with
 * +z (L) / -z (R). Knees are bend angles; the pelvis height follows them.
 *
 * Base poses are single keys. Trick clips are sampled by normalised phase:
 * flips and rolls by rotation progress (see animator.ts), raleys and grabs
 * by the sim's trick phase, crash lead-ins by time. The Luau copy
 * (Anim/RiderPoses.luau) is generated by scripts/gen-luau-data.ts.
 */
const pose = (name: string, key: Omit<PoseClip['keys'][number], 't'>): PoseClip => ({ name, keys: [{ t: 0, ...key }] });

